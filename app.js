// ---------------------------------------------------------------- storage
function normProgress(d) {
  const p = { completed: [], code: {}, last: null, gates: [] };
  if (d && typeof d === "object") {
    if (Array.isArray(d.completed)) p.completed = [...new Set(d.completed.filter(x => typeof x === "string"))];
    if (d.code && typeof d.code === "object") for (const [k, v] of Object.entries(d.code)) if (typeof v === "string") p.code[k] = v;
    if (typeof d.last === "string") p.last = d.last;
    if (Array.isArray(d.gates)) p.gates = [...new Set(d.gates.filter(x => typeof x === "string"))];
    // edit times (ms) let sync with the desktop keep the newest code / last lesson
    if (d.code_t && typeof d.code_t === "object") { p.code_t = {}; for (const [k, v] of Object.entries(d.code_t)) if (typeof v === "number" && v >= 0) p.code_t[k] = v; }
    if (typeof d.last_t === "number") p.last_t = d.last_t;
  }
  return p;
}
function loadProgress() {
  try { return normProgress(JSON.parse(localStorage.getItem(STORE_KEY) || "null")); }
  catch (e) { return normProgress(null); }
}
function saveProgress(pushSoon) {
  // stamp what changed since the last save (sync keeps the newest edit of each lesson's code)
  let old = null;
  try { old = JSON.parse(localStorage.getItem(STORE_KEY) || "null"); } catch (e) {}
  old = old && typeof old === "object" ? old : {};
  const now = Date.now(), oc = old.code && typeof old.code === "object" ? old.code : {};
  S.progress.code_t = S.progress.code_t || {};
  for (const [k, v] of Object.entries(S.progress.code)) if (oc[k] !== v) S.progress.code_t[k] = now;
  if ((old.last || null) !== (S.progress.last || null)) S.progress.last_t = now;
  if (typeof PySync !== "undefined") PySync.dirty(pushSoon ? 2000 : 30000);
  try { localStorage.setItem(STORE_KEY, JSON.stringify(S.progress)); return true; }
  catch (e) { toast("Couldn't save progress on this device (storage full or blocked).", true); return false; }
}

// ---------------------------------------------------------------- Python runner
class PyRunner {
  constructor(onStatus) {
    this.onStatus = onStatus; this.seq = 0; this.job = null; this.chain = Promise.resolve();
    this.version = null; this.restarts = 0; this.spawn();
  }
  spawn() {
    if (this.w) { try { this.w.terminate(); } catch (e) {} }
    this.state = "loading"; this.onStatus("loading");
    this.readyP = new Promise((res, rej) => { this._ready = res; this._fail = rej; });
    this.readyP.catch(() => {});
    const w = new Worker("worker.js", { type: "module" });
    this.w = w;
    w.onmessage = (e) => this.onMsg(e.data, w);
    w.onerror = (e) => {
      if (w !== this.w) return;
      if (e && e.preventDefault) e.preventDefault();
      this.fatal("The Python worker failed to start" + (e && e.message ? ": " + e.message : "."));
    };
  }
  fatal(msg) {
    if (this.state === "loading") { this.state = "error"; this._fail(new Error(msg)); }
    this.onStatus("error", msg);
    if (this.job) this.finish(this.job, this.crashResult(this.job, msg), true);
  }
  onMsg(m, w) {
    if (w !== this.w) return;
    const job = this.job && this.job.id === m.id ? this.job : null;
    if (m.type === "ready") { this.version = m.version; this.state = "ready"; this._ready(); this.onStatus("ready"); }
    else if (m.type === "fatal") this.fatal(m.error);
    else if (m.type === "start" && job) {
      job.timer = setTimeout(() => this.kill("timeout"), job.timeout * 1000);
    } else if (m.type === "stream" && job) {
      if (m.kind === "out") job.out += m.text; else job.err += m.text;
      if (job.onStream) job.onStream(m.kind, m.text);
    } else if (m.type === "result" && job) this.finish(job, m.result, false);
    else if (m.type === "crash" && job) this.finish(job, this.crashResult(job, m.error), true);
  }
  crashResult(job, msg) {
    if (/call stack|stack size|too much recursion/i.test(msg)) {
      // The browser's stack ran out (deep or endless recursion): report it like Python would.
      const err = "RecursionError: maximum recursion depth exceeded\n(Python ran out of stack space in the browser, so it was stopped and restarted.)\n";
      return job.kind === "check"
        ? { status: "error", message: "Your code recursed too deeply (a function kept calling itself), so Python was stopped and restarted.",
            stdout: "", stderr: err, timeout: false, explanation: S.data.recursion_explanation }
        : { stdout: trim(job.out), stderr: trim(job.err) + err, returncode: 1, timeout: false, explanation: S.data.recursion_explanation };
    }
    const text = "Python itself crashed while running this code (" + msg + "). A huge amount of memory " +
      "can do this in the browser. Python has been restarted.";
    return job.kind === "check"
      ? { status: "error", message: text, stdout: trim(job.out), stderr: trim(job.err), timeout: false, explanation: "" }
      : { stdout: trim(job.out), stderr: trim(job.err) + "\n" + text, returncode: null, timeout: false, explanation: "" };
  }
  finish(job, result, restart) {
    if (this.job !== job) return;
    clearTimeout(job.timer); this.job = null;
    if (restart) this.spawn(); else this.onStatus("ready");
    job.resolve(result);
  }
  kill(reason) {
    const job = this.job;
    if (!job) return;
    const t = job.timeout;
    let r;
    if (job.kind === "check") {
      r = reason === "timeout"
        ? { status: "error", stdout: "", stderr: "", timeout: true, message: `Your code took longer than ${t} seconds, so I stopped it.`, explanation: timeoutExplanation(t) }
        : { status: "error", stdout: "", stderr: "", timeout: false, stopped: true, message: "Check stopped.", explanation: "" };
    } else {
      r = reason === "timeout"
        ? { stdout: trim(job.out), stderr: "", returncode: null, timeout: true, explanation: timeoutExplanation(t) }
        : { stdout: trim(job.out), stderr: "", returncode: null, timeout: false, stopped: true, explanation: "" };
    }
    this.finish(job, r, true);   // terminate the worker and start a fresh Python
  }
  stop() { this.kill("stopped"); }
  exec(kind, payload, timeout, onStream) {
    const p = this.chain.then(() => this._exec(kind, payload, timeout, onStream));
    this.chain = p.catch(() => {});
    return p;
  }
  async _exec(kind, payload, timeout, onStream) {
    if (this.state === "error") this.spawn();
    try { await this.readyP; }
    catch (e) {
      const msg = "Python couldn't start: " + e.message + (navigator.onLine ? "" : " (You're offline and the app hasn't finished saving itself for offline use yet.)");
      return kind === "check" ? { status: "error", message: msg, stdout: "", stderr: "", explanation: "" }
                              : { stdout: "", stderr: msg, returncode: null, explanation: "" };
    }
    return new Promise((resolve) => {
      const job = { id: ++this.seq, kind, timeout, onStream, out: "", err: "", resolve, timer: null };
      this.job = job;
      this.onStatus("busy");
      this.w.postMessage({ id: job.id, kind, code: payload.code, test: payload.test || "", timeout });
    });
  }
}
