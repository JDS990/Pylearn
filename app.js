const SMART = /[\u2018\u2019\u201A\u201B\u201C\u201D\u201E\u201F\u2032\u2033]/;
function fixSmartQuotes(ed) {
  if (!SMART.test(ed.value)) return false;
  const s = ed.selectionStart, e = ed.selectionEnd;
  ed.value = ed.value.replace(/[\u2018\u2019\u201A\u201B\u2032]/g, "'").replace(/[\u201C\u201D\u201E\u201F\u2033]/g, '"');
  ed.setSelectionRange(s, e);
  return true;
}
function insertText(ed, text) {
  // execCommand keeps the browser's undo history working; fall back if unsupported.
  let ok = false;
  try { ok = document.execCommand("insertText", false, text); } catch (e) { ok = false; }
  if (!ok) ed.setRangeText(text, ed.selectionStart, ed.selectionEnd, "end");
  changed();
}
function lineRange(ed) {
  const v = ed.value, s = ed.selectionStart, en = ed.selectionEnd;
  const ls = v.lastIndexOf("\n", s - 1) + 1;
  const le = en > s && v[en - 1] === "\n" ? en - 1 : en;
  const lineEnd = v.indexOf("\n", le); return [ls, lineEnd === -1 ? v.length : lineEnd];
}
function indent(ed, dedent) {
  const s = ed.selectionStart, en = ed.selectionEnd;
  if (!dedent && s === en) { insertText(ed, "    "); return; }
  const [ls, le] = lineRange(ed);
  const block = ed.value.slice(ls, le);
  const nb = dedent ? block.split("\n").map(x => x.replace(/^ {1,4}/, "")).join("\n")
                    : block.split("\n").map(x => "    " + x).join("\n");
  if (nb === block) return;
  ed.setSelectionRange(ls, le);
  insertText(ed, nb);
  if (s === en) { const delta = nb.split("\n")[0].length - block.split("\n")[0].length; const p = Math.max(ls, s + delta); ed.setSelectionRange(p, p); }
  else ed.setSelectionRange(ls, ls + nb.length);
}
function insertPair(ed, open, close) {
  const s = ed.selectionStart, e = ed.selectionEnd, sel = ed.value.slice(s, e);
  insertText(ed, open + sel + close);
  if (sel) ed.setSelectionRange(s + 1, s + 1 + sel.length); else ed.setSelectionRange(s + 1, s + 1);
}
const KEYBAR = [
  ["⇥", "Tab (indent)", ed => indent(ed, false)],
  ["⇤", "Un-indent", ed => indent(ed, true)],
  ["( )", "Parentheses", ed => insertPair(ed, "(", ")")],
  ["[ ]", "Square brackets", ed => insertPair(ed, "[", "]")],
  ["{ }", "Curly braces", ed => insertPair(ed, "{", "}")],
  [":", "Colon", ed => insertText(ed, ":")],
  ['"', "Double quote", ed => insertText(ed, '"')],
  ["'", "Single quote", ed => insertText(ed, "'")],
  ["=", "Equals", ed => insertText(ed, "=")],
  ["#", "Comment", ed => insertText(ed, "#")],
  ["_", "Underscore", ed => insertText(ed, "_")],
  ["+", "Plus", ed => insertText(ed, "+")],
  ["*", "Times", ed => insertText(ed, "*")],
];
function setupKeybar(ed) {
  const bar = $("keybar");
  let sel = [ed.value.length, ed.value.length];
  const remember = () => { sel = [ed.selectionStart, ed.selectionEnd]; };
  ["select", "keyup", "input", "blur", "pointerup", "focus"].forEach(ev => ed.addEventListener(ev, remember));
  for (const [label, title, fn] of KEYBAR) {
    const b = document.createElement("button");
    b.type = "button"; b.textContent = label; b.title = title; b.setAttribute("aria-label", title);
    const act = () => {
      if (document.activeElement !== ed) { ed.focus({ preventScroll: true }); ed.setSelectionRange(sel[0], sel[1]); }
      fn(ed); remember();
    };
    let t0 = null, handledByTouch = false;
    b.addEventListener("mousedown", e => e.preventDefault());   // keep focus (and the iOS keyboard) in the editor
    b.addEventListener("touchstart", e => { t0 = [e.touches[0].clientX, e.touches[0].clientY]; }, { passive: true });
    b.addEventListener("touchend", e => {
      const t = e.changedTouches[0];
      if (!t0 || Math.abs(t.clientX - t0[0]) > 10 || Math.abs(t.clientY - t0[1]) > 10) return;  // was a scroll
      e.preventDefault(); handledByTouch = true; act();
    });
    b.addEventListener("click", () => { if (handledByTouch) { handledByTouch = false; return; } act(); });
    bar.appendChild(b);
  }
}
function setupEditor(ed) {
  updateGutter();
  setupKeybar(ed);
  ed.addEventListener("input", () => { fixSmartQuotes(ed); changed(); });
  ed.addEventListener("keydown", e => {
    if (e.key === "Enter" && (e.ctrlKey || e.metaKey)) { e.preventDefault(); e.shiftKey ? doCheck() : doRun(); return; }
    if (S.locked) return;
    const v = ed.value, s = ed.selectionStart, en = ed.selectionEnd;
    if (e.key === "Tab") { e.preventDefault(); indent(ed, e.shiftKey); return; }
    if (e.key === "Enter" && !e.shiftKey && !e.altKey && !e.isComposing) {
      e.preventDefault();
      const ls = v.lastIndexOf("\n", s - 1) + 1;
      const line = v.slice(ls, s);
      let ind = line.match(/^ */)[0];
      if (/:\s*(#.*)?$/.test(line)) ind += "    ";
      if (/^\s*(return|pass|break|continue)\b/.test(line)) ind = ind.slice(4);
      insertText(ed, "\n" + ind); return;
    }
    if (e.key === "Backspace" && s === en && s > 0) {
      const ls = v.lastIndexOf("\n", s - 1) + 1;
      const before = v.slice(ls, s);
      if (before.length >= 4 && /^ +$/.test(before) && before.length % 4 === 0) {
        e.preventDefault(); ed.setSelectionRange(s - 4, s); insertText(ed, "");
        if (ed.selectionStart !== s - 4) { ed.setRangeText("", s - 4, s, "end"); changed(); }
      }
    }
  });
}
function editorCode() { const ed = $("editor"); fixSmartQuotes(ed); return ed.value; }

// ---------------------------------------------------------------- run / check
function setBusy(b) {
  S.busy = b;
  for (const id of ["run", "check", "runEx"]) {
    const el = $(id);
    if (el && !el.dataset.breath) el.disabled = b || (S.locked && id !== "runEx");
  }
  const st = $("stop"); if (st) st.classList.toggle("hidden", !b);
}
function showOutput(box, r) {
  box.classList.remove("hidden");
  let h = "";
  if (r.stdout) h += esc(r.stdout);
  if (r.stderr) h += '<span class="err">' + esc(r.stderr) + "</span>";
  if (!r.stdout && !r.stderr && !r.timeout && !r.stopped) h += '<span class="dim">(no output: use print(...) to see values)</span>';
  const nl = h && !/\n$/.test(r.stdout + r.stderr) ? "\n" : "";
  if (r.timeout) h += '<span class="err">' + nl + "⏱ Stopped: took too long.</span>";
  if (r.stopped) h += '<span class="err">' + nl + "■ Stopped.</span>";
  box.innerHTML = h;
}
function liveOutput(box) {
  box.classList.remove("hidden");
  box.innerHTML = '<span class="dim">' + (runner.state === "ready" ? "Running…" : "Starting Python (the first time can take a few seconds)…") + "</span>";
  let started = false;
  return (kind, text) => {
    if (!started) { box.innerHTML = ""; started = true; }
    if (box.textContent.length > 20000) return;
    if (kind === "out") box.appendChild(document.createTextNode(text));
    else { const sp = document.createElement("span"); sp.className = "err"; sp.textContent = text; box.appendChild(sp); }
  };
}
async function runExample(l) {
  if (S.busy) return;
  const box = $("exOut"), btn = $("runEx"); const old = btn.textContent;
  setBusy(true); btn.textContent = "Running…";
  try { showOutput(box, await runner.exec("run", { code: l.example }, l.web_timeout, liveOutput(box))); }
  finally { setBusy(false); btn.textContent = old; }
}
async function doRun() {
  if (S.busy || S.locked) return;
  flushSave();
  const l = byId[S.current], res = $("result");
  res.innerHTML = '<div class="out" id="runOut"></div><div id="explain"></div>';
  const box = $("runOut"), btn = $("run");
  setBusy(true); btn.textContent = "Running…";
  try {
    const r = await runner.exec("run", { code: editorCode() }, l.web_timeout, liveOutput(box));
    if (l.id !== S.current) return;
    showOutput(box, r);
    if (r.explanation) $("explain").innerHTML = '<div class="banner info md">' + inline(r.explanation) + "</div>";
    box.scrollIntoView({ block: "nearest", behavior: "smooth" });
    return r;
  } finally { setBusy(false); const b = $("run"); if (b) b.textContent = "▶ Run"; }
}
