function gameNow() {
  let st = null;
  try { st = JSON.parse(localStorage.getItem(DRILL_KEY) || "null"); } catch (e) {}
  st = st && typeof st === "object" ? st : {};
  if (typeof st.xp !== "number") st = Object.assign({}, st, { xp: PyGame.backfill(st) });
  return PyGame.summary(st, (id) => !!byId[id]);
}
